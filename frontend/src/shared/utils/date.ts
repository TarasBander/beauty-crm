/**
 * "Сьогодні" в ЛОКАЛЬНОМУ часовому поясі користувача, у форматі YYYY-MM-DD.
 *
 * `new Date().toISOString().slice(0, 10)` (три копії якого раніше жили в
 * Tasks, Payments і Dashboard) бере дату по UTC, а не по місцевому часу.
 * В Україні (UTC+2/+3) це означає, що з півночі до 2-3 ранку локально
 * `toISOString()` все ще показує ВЧОРАШНЮ дату за UTC — задача з дедлайном
 * "сьогодні" могла виглядати простроченою вчора ввечері або ще не
 * простроченою вранці в день дедлайну, залежно від того, як саме
 * порахували "сьогодні" на кожній сторінці.
 *
 * Ця функція натомість читає рік/місяць/день так, як їх показав би
 * годинник користувача.
 */
export function todayLocalISO(): string {
  const now = new Date()
  const y = now.getFullYear()
  const m = String(now.getMonth() + 1).padStart(2, '0')
  const d = String(now.getDate()).padStart(2, '0')
  return `${y}-${m}-${d}`
}
